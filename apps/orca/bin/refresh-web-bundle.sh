#!/usr/bin/env bash
# Refresh from a clean maintainer checkout; publish only after all gates pass.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP="$(cd "$HERE/.." && pwd)"
SOURCE="" OUTPUT="$APP/web-bundle" APPIMAGE_VERSION=""
usage() { echo "usage: $0 --source CLEAN_GIT_CHECKOUT --appimage-version X.Y.Z [--output DIR]" >&2; exit 2; }
while [ "$#" -gt 0 ]; do
  case "$1" in
    --source) [ "$#" -ge 2 ] || usage; SOURCE="$2"; shift 2 ;;
    --output) [ "$#" -ge 2 ] || usage; OUTPUT="$2"; shift 2 ;;
    --appimage-version) [ "$#" -ge 2 ] || usage; APPIMAGE_VERSION="$2"; shift 2 ;;
    *) usage ;;
  esac
done
[ -n "$SOURCE" ] && [ -n "$APPIMAGE_VERSION" ] || usage
[[ "$APPIMAGE_VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "invalid appimage version" >&2; exit 1; }
git -C "$SOURCE" rev-parse --is-inside-work-tree >/dev/null 2>&1 \
  || { echo "source is not a git checkout: $SOURCE" >&2; exit 1; }
[ -z "$(git -C "$SOURCE" status --porcelain --untracked-files=all)" ] \
  || { echo "source checkout is dirty: $SOURCE" >&2; exit 1; }
SOURCE_COMMIT="$(git -C "$SOURCE" rev-parse HEAD)"
[[ "$SOURCE_COMMIT" =~ ^[0-9a-f]{40}$ ]] || { echo "source HEAD is not a full commit" >&2; exit 1; }
SOURCE_DIST="$SOURCE/dist"
[ -f "$SOURCE_DIST/web-index.html" ] && [ -d "$SOURCE_DIST/assets" ] \
  || { echo "source dist is incomplete" >&2; exit 1; }
if find "$SOURCE_DIST" -type l -print -quit | grep -q .; then
  echo "source dist contains a symlink" >&2; exit 1
fi

parent="$(dirname "$OUTPUT")"
install -d "$parent"
stage="$(mktemp -d "$parent/.orca-web-bundle.XXXXXX")"
cleanup() { rm -rf "$stage"; }
trap cleanup EXIT
install -d "$stage/dist"
cp -a "$SOURCE_DIST/." "$stage/dist/"
cp "$APP/web-bundle/README.md" "$stage/README.md"
cp "$APP/web-bundle/public-scrub.json" "$stage/public-scrub.json"

python3 - "$stage/dist" "$stage/public-scrub.json" <<'PY'
import json, pathlib, sys
dist = pathlib.Path(sys.argv[1])
rules = json.loads(pathlib.Path(sys.argv[2]).read_text(encoding="utf-8"))
namespace_old = "orca-web."
namespace_new = rules.pop(namespace_old)
anchors = ["재연결 중…", "install-canary-gate.sh", "externalSlots 미설정?"]
touched = []
for path in sorted(p for p in dist.rglob("*") if p.is_file()):
    try:
        text = path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        continue
    if not any(anchor in text for anchor in anchors):
        continue
    original = text
    for old in sorted(rules, key=len, reverse=True):
        new = rules[old]
        text = text.replace(old, new)
    if text != original:
        text = text.replace(namespace_old, namespace_new)
        touched.append(path)
    path.write_text(text, encoding="utf-8")
for path in touched:
    text = path.read_text(encoding="utf-8")
    for old in [*rules, namespace_old]:
        if old in text:
            print(f"{path}: residual scrub source {old!r}", file=sys.stderr)
            raise SystemExit(1)
PY

mapfile -t entry_assets < <(grep -oE 'assets/web-index-[A-Za-z0-9_-]+\.js' "$stage/dist/web-index.html" | sort -u)
[ "${#entry_assets[@]}" = 1 ] || { echo "source body has no unique hashed web-index asset" >&2; exit 1; }
entry="${entry_assets[0]}"
[ -f "$stage/dist/$entry" ] || { echo "hashed entry asset is absent: $entry" >&2; exit 1; }
python3 - "$stage/dist/web-index.html" <<'PY' || { echo "source body is incomplete" >&2; exit 1; }
import pathlib, re, sys
text = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
raise SystemExit(0 if re.search(r"</body>\s*</html>\s*$", text, re.I) else 1)
PY

count="$(find "$stage/dist" -type f | wc -l | tr -d ' ')"
tree_sha="$(cd "$stage/dist" && find . -type f | LC_ALL=C sort | xargs sha256sum | sha256sum | cut -d' ' -f1)"
cat > "$stage/VERSION" <<EOF
# Generated by apps/orca/bin/refresh-web-bundle.sh. Do not edit pins by hand.
orca-appimage-version: $APPIMAGE_VERSION
web-source-commit: $SOURCE_COMMIT
web-index-asset: $entry
dist-file-count: $count
dist-tree-sha256: $tree_sha
EOF
"$HERE/verify-web-bundle.sh" --bundle "$stage"

backup=""
if [ -e "$OUTPUT" ]; then backup="${OUTPUT}.refresh-backup.$$"; mv "$OUTPUT" "$backup"; fi
if mv "$stage" "$OUTPUT"; then
  [ -z "$backup" ] || rm -rf "$backup"
  trap - EXIT
  printf '[orca-bundle] refreshed %s from %s\n' "$OUTPUT" "$SOURCE_COMMIT" >&2
else
  [ -z "$backup" ] || mv "$backup" "$OUTPUT"
  exit 1
fi
